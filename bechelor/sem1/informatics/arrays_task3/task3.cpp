#include <iostream>
#include <clocale>
using namespace std;

int main(){
    setlocale(LC_ALL, ".UTF8");
    // Инициализация двумерного массива (матрицы) 3x3
     int m[3][3] = {
        {2, 53, 43},
        {7, 21, 54},
        {19, 99, 23}
    }, 
    // Объявление и инициализация переменных:
    // max — текущий максимальный элемент (начинаем с первого элемента матрицы m[0][0])
    // ii, ij — индексы строки и столбца максимального элемента
    max = m[0][0], ii = 0, ij = 0;

    // Внешний цикл по строкам матрицы (индекс i от 0 до 2)
    for (int i = 0; i < 3; i++)
    {   
        // Внутренний цикл по столбцам матрицы (индекс j от 0 до 2)
        for (int j = 0; j < 3; j++)
        {   
            // Если текущий элемент больше текущего максимума
            if (m[i][j] > max){

                max = m[i][j]; // Обновляем значение максимума
                ii = i; // Сохраняем индекс строки
                ij = j; // Сохраняем индекс столбца
            }
    }
    }
    // Вывод найденного максимального элемента и его позиций (индексов) в матрице
    cout << "Максимальный элемент: " << max << " Индекс по строке: " << ii  << " по столбцу: " << ij << endl;
    return 0;

}
