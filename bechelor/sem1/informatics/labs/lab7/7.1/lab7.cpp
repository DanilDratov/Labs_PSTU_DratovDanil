#include <iostream>
#include <clocale>

using namespace std;

// Первая перегруженная функция: умножение двух вещественных чисел
double mult(double a, double b) {
    return a * b; // Возвращаем произведение двух вещественных чисел
}

// Вторая перегруженная функция: умножение двух комплексных чисел
// Первое число: (r1 + i1*i), второе число: (r2 + i2*i)
// Результат записывается в ссылочные переменные resR (действительная часть) и resI (мнимая часть)
void mult(double r1, double i1, double r2, double i2, double &resR, double &resI) {
    resR = r1 * r2 - i1 * i2;
    resI = r1 * i2 + i1 * r2;
}

int main() {

    setlocale(LC_ALL, ".UTF8");

    // 1. Проверка умножения вещественных чисел
    double x = 4.5; // Первое вещественное число
    double y = 2.0; // Второе вещественное число

    // Вызов первой версии функции mult (компилятор выбирает ее по двум аргументам)
    double p = mult(x, y);
    cout << "Умножение вещественных чисел:" << endl;
    cout << x << " * " << y << " = " << p << endl << endl;

    // 2. Проверка умножения комплексных чисел
    double a1 = 2.0, b1 = 3.0; // Первое комплексное число: 2 + 3i
    double a2 = 4.0, b2 = -5.0; // Второе комплексное число: 4 - 5i
    double rr = 0.0, ri = 0.0; // Переменные для хранения действительной и мнимой частей результата

    // Вызов второй версии функции mult (компилятор выбирает ее по шести аргументам)
    mult(a1, b1, a2, b2, rr, ri);

    cout << "Умножение комплексных чисел:" << endl;
    cout << "Первое число: " << a1 << " + " << b1 << "i" << endl;
    cout << "Второе число: " << a2 << " " << b2 << "i" << endl;

    // Вывод результата с учетом знака мнимой части
    cout << "Результат умножения: " << rr;
    if (ri >= 0) {
        cout << " + " << ri << "i" << endl;
    } else {
        cout << " - " << -ri << "i" << endl;
    }

    return 0;
}
