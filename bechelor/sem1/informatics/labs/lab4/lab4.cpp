#include <iostream>
#include <cstdlib>
#include <clocale>

using namespace std;

int main(){

    setlocale(LC_ALL,".UTF8");

    const int MAX_SIZE = 200;
    int arr[MAX_SIZE];

    // Автоматически задаем начальный размер массива (например, 10 элементов)
    int n = 10;

    // 1. Автоматическое заполнение массива случайными числами в диапазоне от -20 до 20
    for (int i = 0; i < n; i++) {
        arr[i] = rand() % 41 - 20; 
    }


    // Печать исходного массива
    cout << "1. Исходный массив (размер " << n << "):" << endl;
    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";
    }
    cout << endl << endl;

    // 2. Удаление всех элементов, кратных 7
    for (int i = 0; i < n; ) {
        // Проверяем, делится ли элемент на 7 (и исключаем ноль)
        if (arr[i] != 0 && arr[i] % 7 == 0) {
            // Сдвигаем все элементы влево на одну позицию
            for (int j = i; j < n - 1; j++) {
                arr[j] = arr[j + 1];
            }
        n--; // Уменьшаем реальный размер массива
        }
        else {
            i++; // Переходим к следующему элементу, если удаления не было
        }
    }

    // Печать массива после удаления
    cout << "2. Массив после удаления элементов, кратных 7 (размер " << n << "):" << endl;
    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";
    }
    cout << endl << endl;

    // 3. Добавление элемента со значением 0 после каждого нечетного элемента
    for (int i = 0; i < n; i++) {
        // Проверяем элемент на нечетность (с учетом отрицательных чисел через abs)
        if (abs(arr[i]) % 2 != 0) {
            // Сдвигаем элементы вправо, чтобы освободить место для нового нуля
            for (int j = n; j > i + 1; j--) {
                arr[j] = arr[j - 1];
            }
            arr[i + 1] = 0; // Вставляем ноль сразу после нечетного элемента
            n++; // Увеличиваем размер массива
            i++; // Пропускаем только что вставленный ноль, чтобы не зациклиться
        }
    }

    // 4. Печать итогового массива
    cout << "3. Итоговый массив после добавления 0 (размер " << n << "):" << endl;
    for (int i = 0; i < n; i++) {
        cout << arr[i] << " ";
    }
    cout << endl;


    return 0;

}