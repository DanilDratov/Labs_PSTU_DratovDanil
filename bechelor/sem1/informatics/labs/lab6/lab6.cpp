#include <iostream>
#include <cstdio> // Подключение библиотеки для работы функции gets_s()
#include <cstring> // Подключение библиотеки для работы со строками (strlen, strcmp, strcpy)
#include <clocale>

using namespace std; 

int main() {

    setlocale(LC_ALL, ".UTF8");

    char s[256]; // Символьный массив для хранения введенной строки

    cout << "Введите строку: ";
    gets_s(s, sizeof(s)); // Ввод строки с пробелами с клавиатуры

    char first[256] = ""; // Массив для хранения эталонного первого слова
    char word[256] = ""; // Буферный массив для накопления текущего слова
    int k = 0; // Индекс текущей буквы в буферном слове
    bool First = false; // Флаг, показывающий, найдено ли уже первое слово
    int count = 0; // Счетчик найденных совпадений

    cout << "\nСлова, совпадающие с первым словом:" << endl;

    int len = strlen(s); // Вычисляем общую длину введенной строки

    // Посимвольный проход по всей введенной строке
    for (int i = 0; i <= len; i++) {
        // Если текущий символ не пробел и не конец строки ('\0')
        if (s[i] != ' ' && s[i] != '\0') {
            word[k] = s[i]; // Записываем букву в буферное слово
            k++; // Сдвигаем индекс буквы в буфере
        }
        else {
            // Если встретился пробел или конец строки, и в буфере накопилось слово
            if (k > 0) {
                word[k] = '\0'; // Завершаем формирование строки нуль-терминатором

                if (!First) {
                    strcpy(first, word); // Копируем первое слово в переменную-эталон
                    First = true; // Отмечаем, что эталон найден
                }

                // Сравниваем текущее слово с первым словом (strcmp возвращает 0 при совпадении)
                if (strcmp(word, first) == 0) {
                    cout << word << endl; // Выводим совпавшее слово на экран
                    count++; // Увеличиваем счетчик совпадений
                }

                k = 0; // Обнуляем индекс буфера для чтения следующего слова
            }
        }
    }
    // Вывод итоговой статистики
    cout << "\nПервое слово: " << first << endl;
    cout << "Всего совпадений (включая первое слово): " << count << endl;

    return 0;
}