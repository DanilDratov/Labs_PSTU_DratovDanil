#include <iostream>
#include <cstdlib>
#include <clocale>

using namespace std;

int main(){

    setlocale(LC_ALL,".UTF8");

    const int N = 3; // Размер квадратной матрицы (3 на 3)
    const double EPS = 0.0001; // Допустимая погрешность для сравнения вещественных чисел

    // Задаем вещественную матрицу (пример ортонормированной матрицы поворота)
    double m[N][N] = {
        { 0.6, -0.8, 0.0 },
        { 0.8,  0.6, 0.0 },
        { 0.0,  0.0, 1.0 }
    };

    // Построчный вывод исходной матрицы на экран
    cout << "Исходная матрица:" << endl;
    for (int i = 0; i < N; i++){
        for (int j = 0; j < N; j++){
            cout << m[i][j] << "    ";
        }
        cout << endl;
    }
    cout << endl;

    bool ok = true; // Флаг ортонормированности (изначально считаем, что условие выполняется)

    // Перебираем все возможные пары строк (первая строка i, вторая строка j)
    for (int i = 0; i < N; i++){
        for (int j = 0; j < N; j++){

            double sp = 0.0; // Переменная для накопления скалярного произведения строк i и j

            // Вычисляем скалярное произведение: сумма произведений соответствующих элементов
            for (int k = 0; k < N; k++) {
                sp += m[i][k] * m[j][k];
            }

            // Проверяем условие в зависимости от того, одинаковые это строки или разные
            if (i == j) {
                // Скалярное произведение строки самой на себя должно быть равно 1
                if (abs(sp - 1.0) > EPS) {
                    ok = false; // Нарушено условие нормированности
                }
            }
            else{
                // Скалярное произведение различных строк должно быть равно 0
                if (abs(sp) > EPS) {
                    ok = false; // Нарушено условие ортогональности
                }
            }
        }
    }
    // Вывод итогового результата проверки
    if (ok){
        cout << "Результат: матрица является ортонормированной." << endl;
    }
    else {
        cout << "Результат: матрица не является ортонормированной." << endl;
    }

    return 0;
}