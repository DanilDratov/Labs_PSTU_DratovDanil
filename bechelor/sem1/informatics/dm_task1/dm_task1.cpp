#include <iostream>
#include <cstdlib>
#include <ctime>

using namespace std;

// Заполняем массив случайными числами от 0 до 99
void fillNums(int* data, int len) {
    for (int idx = 0; idx < len; ++idx) { // Идём по всем элементам от 0 до len - 1
        data[idx] = rand() % 100; // Записываем случайное число в диапазоне 0..99
    }
}

// Печатаем элементы массива в одну строку
void printNums(const int* data, int len) {
    if (!data || len <= 0) return; // Защита: если указатель пустой или длина <= 0 — выходим

    for (int idx = 0; idx < len; ++idx) { // Проходим по каждому элементу массива
        cout << data[idx] << (idx + 1 < len ? " " : ""); // Выводим элемент и пробел между элементами
    }
    cout << '\n'; // Переводим строку в конце вывода массива
}

// Функция увеличения массива на 1 элемент
// int*& data — ссылка на указатель (чтобы поменять адрес массива в вызывающем коде)
// int& len — ссылка на размер (чтобы обновить длину массива в вызывающем коде)
void addSlot(int*& data, int& len) {
    int nextLen = len + 1; // Вычисляем новый размер массива (на 1 больше текущего)
    int* temp = new (nothrow) int[nextLen]; // Выделяем память под новый увеличенный массив
    if (!temp) { // Проверяем, хватило ли памяти
        cerr << "Memory allocation error\n"; // Сообщаем об ошибке
        return; // Выходим, не ломая старый массив
    } 

    int k = 0; // Индекс для копирования элементов
    while (k < len) { // Копируем все старые элементы из data в temp
        temp[k] = data[k]; // Переносим элемент с индексом k
        ++k;  // Переходим к следующему элементу
    }

    delete[] data; // Удаляем старый массив, чтобы не было утечки памяти
    data = temp;  // Перенаправляем указатель data на новый массив
    len = nextLen; // Обновляем переменную размера новым значением
}


// Функция уменьшения массива на 1 элемент
void removeLast(int*& data, int& len) {
    if (len <= 1) { // Если в массиве 1 элемент или меньше — сжимать дальше нельзя
        cout << "Array is too small to shrink\n"; // Выводим предупреждение
        return; // Выходим без изменений
    }

    int nextLen = len - 1; // Вычисляем новый размер мас сива (на 1 меньше текущего)
    int* temp = new (nothrow) int[nextLen]; // Выделяем память под новый укороченный массив
    if (!temp) { // Проверяем выделение памяти
        cerr << "Memory allocation error\n"; // Сообщаем об ошибке
        return; // Выходим без изменений
    }

    for (int idx = 0; idx < nextLen; ++idx) { // Копируем только первые nextLen элементов (последний отбрасывается)
        temp[idx] = data[idx]; // Переносим элемент в новый массив
    }

    delete[] data; // Освобождаем память старого массива
    data = temp; // Заменяем старый указатель на адрес нового массива
    len = nextLen; // Обновляем размер массива
}

int main() {

    srand(static_cast<unsigned int>(time(nullptr))); // Инициализируем генератор случайных чисел по времени

    int len = 5; // Начальный размер массива — 5 элементов
    int* nums = new (nothrow) int[len]; // Выделяем динамический массив из 5 целых чисел
    if (!nums) { // Проверяем, выделилась ли память
        cerr << "Memory allocation error\n"; // Сообщаем об ошибке
        return 1; // Завершаем программу с ошибкой
    }

    fillNums(nums, len); // Заполняем массив случайными числами
    cout << "Start: "; // Печатаем подпись перед исходным массивом
    printNums(nums, len); // Выводим массив до уменьшения

    removeLast(nums, len); // Уменьшаем массив на 1 элемент (становится 4 элемента)
    cout << "After shrink: "; // Печатаем подпись перед изменённым массивом
    printNums(nums, len); // Выводим массив после уменьшения

    delete[] nums; // Освобождаем память, выделенную под итоговый массив
    nums = nullptr; // Зануляем указатель после удаления памяти

    return 0; // Завершаем программу успешно
} 