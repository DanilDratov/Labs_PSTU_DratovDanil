#include <iostream>
#include <cmath>
#include <iomanip>
using namespace std;

int main() {


    // 1. Инициализация параметров: интервал [a, b], шаги разбиения, 
    // количество слагаемых (n) и требуемая точность (eps)
    double a = 1.0;
    double b = 2.0;
    int k = 10;
    double h = (b - a) / k;
    int n = 15;
    double eps = 0.0001;

    // Настраиваем вывод вещественных чисел (фиксированная точка, 6 знаков после запятой)
    cout << fixed << setprecision(6);


    // 2. Внешний цикл: последовательно вычисляем значения для каждого x на отрезке от a до b
    for (int i = 0; i <= k; i++) {
        double x = a + i * h;

        double s1 = 1.0;      
        double t1 = 1.0;
        int j = 1;


        // 3. Первый метод: вычисление суммы ряда для фиксированного числа слагаемых (n = 15)
        while (j <= n){
            t1 *= x / j;  // Рекуррентная формула для получения следующего слагаемого     
            s1 += t1;     // Накопление общей суммы
            j++;
        }
        
        double s2 = 1.0;
        double t2 = 1.0;
        j = 1;
        double cur = abs(t2);


        // 4. Второй метод: вычисление суммы ряда с заданной точностью eps
        while(cur >= eps) {
            t2 *= x / j;  // Вычисление очередного элемента ряда
            cur = abs(t2);  // Оценка текущей погрешности (модуль слагаемого)

            if (cur >= eps) {
                s2 += t2; // Прибавление слагаемого к сумме, если точность еще не достигнута
            }
            j++;
        }
        
        // 5. Эталонное значение функции (в качестве точного значения используем сумму ряда s1)
        double y = s1;


        // 6. Вывод результатов текущей итерации
        cout << "X=" << x << "    SN=" << s1 << "    SE="  << s2 << "    Y=" << y << endl;
    }
    
    return 0;
}  