#include <iostream>
#include <cmath>
#include <iomanip>

using namespace std;

int main() {
    //===ВЫЧИСЛЕНИЯ С ТИПОМ ДАННЫХ FLOAT
    {
        //Инициализация исходных параметров для float
    float a = 1000.0;
    float b = 0.0001;
    float c,d,e,x,y;

    // Вывод с фиксированной точкой и 6 знаками после запятой
    cout << fixed << setprecision(6);

    //Вычисление первой части числителя: c = (a - b)^3
    c = pow(a-b,3);
    //Вычисление второй части числителя: d = a^3 - 3 * a^2 * b
    d = pow(a,3) - 3.0 * pow(a,2) * b;
    //Вычисление знаменателя: e = b^3 - 3 * a * b^2
    e = pow(b,3) - 3.0 * a * pow(b,2);
    //Находим числитель целиком : x = c - d
    x = c - d;
    //Итоговый расчет всей формулы: деление числителя на знаменатель
    y = x / e;


    //Вывод результатов в консоль
    cout << "===FLOAT===" << endl;
    cout << "c = " << c << endl;
    cout << "d = " << d << endl;
    cout << "e = " << e << endl;
    cout << "x = " << x << endl;
    cout << "y = " << y << endl;
    }

    //===ВЫЧИСЛЕНИЯ С ТИПОМ ДАННЫХ DOUBLE
    {
        //Инициализация исходных параметров для double
        double a = 1000.0;
        double b = 0.0001;
        double c,d,e,x,y;

        // Вывод с фиксированной точкой и 6 знаками после запятой
        cout << fixed << setprecision(6);
    
        //Вычисление первой части числителя: c = (a - b)^3
        c = pow(a-b,3);
        //Вычисление второй части числителя: d = a^3 - 3 * a^2 * b
        d = pow(a,3) - 3.0 * pow(a,2) * b;
        //Вычисление знаменателя: e = b^3 - 3 * a * b^2
        e = pow(b,3) - 3.0 * a * pow(b,2);
        //Находим числитель целиком : x = c - d
        x = c - d;
        //Итоговый расчет всей формулы: деление числителя на знаменатель
        y = x / e;

        //Вывод результатов в консоль
        cout << "===DOUBLE===" << endl;
        cout << "c = " << c << endl;
        cout << "d = " << d << endl;
        cout << "e = " << e << endl;
        cout << "x = " << x << endl;
        cout << "y = " << y << endl;
    }

    return 0;
}