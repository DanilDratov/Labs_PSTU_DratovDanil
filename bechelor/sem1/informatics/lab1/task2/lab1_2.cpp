#include <iostream>
#include <clocale>
using namespace std;

int main(){
    //Подключение русской локали
    setlocale(LC_ALL, ".UTF8");
    int m,n;
    cout << "Введите значение m: ";
    cin >> m;//Ввод переменной m с клавиатуры
    cout << "Введите значение n: ";
    cin >> n;//Ввод переменной n с клавиатуры
    cout << endl;

    // === ВЫРАЖЕНИЕ 1: --m-++n ===
    {
        int m1 = m, n1 = n;
        // Шаг 1: Префиксный инкремент увеличивает n1 на 1 
        // Шаг 2: Двойной унарный минус применяется к m1
        // Шаг 3: Вычисление итогового значения выражения
        int r1 = --m1 - (++n1);
        cout << "1. Выражение '--m-++n' = " << r1 <<  endl;

    }
    // === ВЫРАЖЕНИЕ 2: m*n<n++ ===
    {
        int m2 = m, n2 = n;
        // Шаг 1: Умножение m2 на n2
        // Шаг 2: Сравнение со старым n2, после n2 увеличивается (постфиксный инкремент) 
        bool r2 = (m2*n2 < n2++);
        cout << "1. Выражение 'm*n<n++' = " << r2 << "(0 - ложь, 1 - истина)" << endl;

    }
    // === ВЫРАЖЕНИЕ 2: n-->m++ ===
    {
        int m3 = m, n3 = n;
        // Шаг 1: Сравнение текущих значений n3 и m3
        // Шаг 2: Постфиксные декремент n3-- и инкремент m3++ срабатывают после сравнения
        bool r3 = (n3-- > m3++);
        cout << "1. Выражение 'n-->m++' = " << r3 << "(0 - ложь, 1 - истина)" << endl;
    }

    return 0;
}