#include <iostream>
#include <clocale>
using namespace std;

int main(){
    setlocale(LC_ALL, ".UTF8");

    // Флаг-признак нарушения порядка (false — последовательность упорядочена, true — найдено нарушение)
    bool f = false;
    
    // Инициализация массива из 10 элементов, а также переменных:
    // i — индекс текущего элемента
    // a, b — вспомогательные переменные для сравнения соседних элементов
    int m[10] = {28,12,43,245,65,43,12,2,76,4}, i = 0, a , b;

    // Цикл проверки: выполняется, пока флаг f == false (нарушений еще не было) 
    // и индекс i не вышел за границы (до предпоследнего элемента, т.к. сравниваем с i + 1)
    while ((!f) && (i < 10 - 1)) {
        a = m[i]; // Текущий элемент
        b = m[i+1]; // Следующий элемент

        // Если текущий элемент больше или равен следующему, 
        // то условие возрастания нарушено
        if (a >= b) {
        f = true;
    }
        i += 1;
    }

    // Вывод результата на основе значения флага f
    if (f) { 
        cout <<"Последовательность не упорядочена";
    }
    else { 
        cout << "Последовательность упорядочена";
    }
    return 0;
}