#include <iostream>

using namespace std;

const int size_arr = 8;           // Размер шахматной доски (8 на 8 клеток)
int arr[size_arr][size_arr]{};    // Двумерный массив-доска, изначально заполненный нулями (0 - пусто, 1)- ферзь)
int attempt = 0;                  // Счетчик найденных правильных расстановок

// Функция для вывода текущего состояния шахматной доски на экран
void show()
{
    for (int i = 0; i < size_arr; i++) // Проход по всем строкам доски
    {
        for (int j = 0; j < size_arr; j++) // Проход по всем столбцам текущей строки
        {
            // Если в клетке стоит 1, выводим "! " (ферзь), если 0 — выводим "# " (пустая клетка)
            cout << (arr[i][j] ? "! " : "# ");
        }
        cout << endl; // Переход на новую строку после вывода одного ряда доски
    }
}

// Функция проверки безопасности клетки (row, col) перед установкой ферзя
bool check(int row, int col)
{
    // 1. Проверка вертикали вверх: нет ли другого ферзя в этом же столбце
    for (int i = 0; i < row; i++)
    {
        if (arr[i][col]) // Если в ячейке выше уже стоит 1
            return false; // Клетка под боем, ставить нельзя
    }
    // 2. Проверка левой верхней диагонали (шагаем вверх и влево, пока не выйдем за край доски)
    for (int i = 1; row - i >= 0 && col - i >= 0; i++)
    {
        if (arr[row - i][col - i]) // Если на диагонали найден ферзь
            return false; // Клетка под боем
    }
    // 3. Проверка правой верхней диагонали (шагаем вверх и вправо до края доски)
    for (int i = 1; row - i >= 0 && col + i < size_arr; i++)
    {
        if (arr[row - i][col + i]) // Если на диагонали найден ферзь
            return false; // Клетка под боем
    }

    return true; // Все три направления чистые, клетка безопасна
}

// Главная рекурсивная функция для расстановки ферзей по строкам (метод поиска с возвратом)
void game(int row)
{
    // Базовое условие выхода: если дошли до 8-й строки, значит все 8 ферзей успешно расставлены
    if (row == size_arr)
    {
        cout << "Placement #" << ++attempt << endl << endl; // Увеличиваем счетчик и выводим номер варианта
        show(); // Печатаем найденную расстановку на экран
        cout << endl; // Пустая строка для разделения вариантов
        return; // Завершаем текущую ветку рекурсии
    }

    // Перебираем по очереди все столбцы (клетки) в текущей строке row
    for (int col = 0; col < size_arr; col++)
    {
        // Проверяем, можно ли безопасно поставить ферзя в клетку (row, col)
        if (check(row, col))
        {
            arr[row][col] = 1; // Ставим ферзя в текущую клетку
            game(row + 1);     // Рекурсивно переходим к расстановке ферзя в следующей строке
            arr[row][col] = 0; // Откат: убираем ферзя после проверки ветки, чтобы попробовать следующий столбец
        }
    }
}

int main()
{
    game(0);  // Запускаем расстановку с самой первой (нулевой) строки
    return 0; // Завершение работы программы
}