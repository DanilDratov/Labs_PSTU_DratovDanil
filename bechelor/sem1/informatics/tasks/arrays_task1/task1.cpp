#include <iostream>
#include <clocale>
using namespace std;

int main(){
    setlocale(LC_ALL, ".UTF8");
    // Инициализация массива из 15 элементов
    // max, min     — текущее максимальное и минимальное значения (начинаем с первого элемента m[0])
    // indmax, indmin — индексы найденного максимума и минимума в массиве
    // nmax, nmin     — счетчики количества повторений максимума и минимума
    int m[15] = {3,5,7,8,12,3,8,44,12,16,12,53,65,42,76};
    int max = m[0], min = m[0], indmax = 0, indmin = 0, nmax = 1, nmin = 1;

    // Перебор элементов массива от 0 до 14 включительно
    for (int i = 0; i < 15; i++) {
        if (m[i] > max) {
            // Найден новый максимум: обновляем значение, индекс и сбрасываем счетчик повторов
            max = m[i];
            indmax = i;
            nmax =  1;
        }
        else if(m[i] < min) {
            // Найден новый минимум: обновляем значение, индекс и сбрасываем счетчик повторов
            min = m[i];
            indmin = i;
            nmin = 1;
        }
        else if(m[i] == max) {nmax++;}
        // Элемент равен текущему максимуму — увеличиваем количество повторов
        else if(m[i ] == min) {nmin++;}
        // Элемент равен текущему минимуму — увеличиваем количество повторов
    }

    
    cout<<"max = "<< max <<" max index =  "<< indmax <<" max number =  "<< indmax + 1 <<endl;
    cout<<"min = "<< min <<" min index =  "<< indmin <<" min number =  "<< indmin + 1 <<endl;
    // Вывод сообщений о дубликатах, если максимальное или минимальное значение встретилось больше одного раза
    if (nmax > 1) {
        cout<<"Одинаковые max: "<< nmax <<endl;
    }
    if (nmin > 1) {
        cout<<"Одинаковые min: "<< nmin <<endl;
    }
    return 0;
}   